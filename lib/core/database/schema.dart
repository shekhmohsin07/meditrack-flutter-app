/// Complete SQLite schema (version 1). Every synced table has:
/// id (UUID), created_at, updated_at, deleted_at (soft delete / tombstone),
/// sync_status ('pending' | 'synced').
class Schema {
  Schema._();
  static const int version = 1;

  static const String _base = '''
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    deleted_at TEXT,
    sync_status TEXT NOT NULL DEFAULT 'pending' ''';

  static final List<String> createStatements = [
    '''CREATE TABLE users (
      id TEXT PRIMARY KEY,
      email TEXT NOT NULL,
      display_name TEXT NOT NULL,
      photo_url TEXT,
      phone TEXT,
      $_base)''',
    '''CREATE TABLE family_members (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      relationship TEXT NOT NULL,
      birth_date TEXT,
      photo_path TEXT,
      caregiver_consent INTEGER NOT NULL DEFAULT 0 CHECK (caregiver_consent IN (0,1)),
      consent_at TEXT,
      $_base)''',
    '''CREATE TABLE medicines (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id TEXT REFERENCES family_members(id) ON DELETE CASCADE,
      name TEXT NOT NULL CHECK (length(trim(name)) > 0),
      dosage TEXT NOT NULL,
      type TEXT NOT NULL CHECK (type IN ('tablet','capsule','syrup','injection','drops','cream','other')),
      food_instruction TEXT NOT NULL CHECK (food_instruction IN ('before_food','after_food','with_food','empty_stomach','as_instructed')),
      start_date TEXT NOT NULL,
      end_date TEXT,
      image_path TEXT,
      status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','completed')),
      notes TEXT,
      $_base)''',
    '''CREATE TABLE schedules (
      id TEXT PRIMARY KEY,
      medicine_id TEXT NOT NULL REFERENCES medicines(id) ON DELETE CASCADE,
      frequency TEXT NOT NULL CHECK (frequency IN ('daily','weekly','custom')),
      days_of_week TEXT NOT NULL DEFAULT '1,2,3,4,5,6,7',
      start_date TEXT NOT NULL,
      end_date TEXT,
      is_paused INTEGER NOT NULL DEFAULT 0 CHECK (is_paused IN (0,1)),
      $_base)''',
    '''CREATE TABLE schedule_times (
      id TEXT PRIMARY KEY,
      schedule_id TEXT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
      time_of_day TEXT NOT NULL CHECK (time_of_day GLOB '[0-2][0-9]:[0-5][0-9]'),
      $_base)''',
    '''CREATE TABLE medicine_logs (
      id TEXT PRIMARY KEY,
      medicine_id TEXT NOT NULL REFERENCES medicines(id) ON DELETE CASCADE,
      schedule_time_id TEXT REFERENCES schedule_times(id) ON DELETE SET NULL,
      member_id TEXT REFERENCES family_members(id) ON DELETE SET NULL,
      scheduled_at TEXT NOT NULL,
      action_at TEXT,
      status TEXT NOT NULL CHECK (status IN ('pending','taken','missed','skipped','snoozed')),
      $_base,
      UNIQUE (medicine_id, scheduled_at))''',
    '''CREATE TABLE inventory (
      id TEXT PRIMARY KEY,
      medicine_id TEXT NOT NULL UNIQUE REFERENCES medicines(id) ON DELETE CASCADE,
      initial_quantity REAL NOT NULL CHECK (initial_quantity >= 0),
      remaining_quantity REAL NOT NULL CHECK (remaining_quantity >= 0),
      low_stock_threshold REAL NOT NULL DEFAULT 5,
      dose_quantity REAL NOT NULL DEFAULT 1,
      expiry_date TEXT,
      $_base)''',
    // Extra table (beyond the 16 required) for "stock history". UNIQUE(log_id)
    // guarantees one intake can never deduct stock twice.
    '''CREATE TABLE stock_history (
      id TEXT PRIMARY KEY,
      inventory_id TEXT NOT NULL REFERENCES inventory(id) ON DELETE CASCADE,
      log_id TEXT UNIQUE REFERENCES medicine_logs(id) ON DELETE SET NULL,
      change_amount REAL NOT NULL,
      reason TEXT NOT NULL CHECK (reason IN ('initial','intake','manual','refill')),
      $_base)''',
    '''CREATE TABLE health_records (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id TEXT REFERENCES family_members(id) ON DELETE CASCADE,
      type TEXT NOT NULL CHECK (type IN ('blood_pressure','blood_glucose','weight','note','history')),
      value1 REAL,
      value2 REAL,
      unit TEXT,
      note TEXT,
      recorded_at TEXT NOT NULL,
      $_base)''',
    '''CREATE TABLE notifications (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      medicine_id TEXT REFERENCES medicines(id) ON DELETE CASCADE,
      notification_int_id INTEGER NOT NULL,
      title TEXT NOT NULL,
      body TEXT NOT NULL,
      scheduled_at TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','shown','cancelled')),
      $_base,
      UNIQUE (notification_int_id))''',
    '''CREATE TABLE doctors (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      specialty TEXT,
      phone TEXT,
      hospital TEXT,
      $_base)''',
    '''CREATE TABLE appointments (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id TEXT REFERENCES family_members(id) ON DELETE CASCADE,
      doctor_id TEXT REFERENCES doctors(id) ON DELETE SET NULL,
      hospital TEXT,
      appointment_at TEXT NOT NULL,
      notes TEXT,
      reminder_minutes INTEGER NOT NULL DEFAULT 60,
      status TEXT NOT NULL DEFAULT 'upcoming' CHECK (status IN ('upcoming','completed','cancelled')),
      $_base)''',
    '''CREATE TABLE allergies (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id TEXT REFERENCES family_members(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      reaction TEXT,
      $_base)''',
    '''CREATE TABLE emergency_contacts (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      relationship TEXT,
      $_base)''',
    '''CREATE TABLE prescriptions (
      id TEXT PRIMARY KEY,
      user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id TEXT REFERENCES family_members(id) ON DELETE CASCADE,
      image_path TEXT NOT NULL,
      remote_url TEXT,
      note TEXT,
      issued_at TEXT,
      $_base)''',
    '''CREATE TABLE sync_queue (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      entity_table TEXT NOT NULL,
      entity_id TEXT NOT NULL,
      operation TEXT NOT NULL CHECK (operation IN ('upsert','delete')),
      attempts INTEGER NOT NULL DEFAULT 0,
      last_error TEXT,
      created_at TEXT NOT NULL,
      UNIQUE (entity_table, entity_id))''',
    '''CREATE TABLE app_settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL,
      updated_at TEXT NOT NULL)''',
    // Indexes
    'CREATE INDEX idx_medicines_user ON medicines(user_id, deleted_at)',
    'CREATE INDEX idx_medicines_member ON medicines(member_id)',
    'CREATE INDEX idx_schedules_medicine ON schedules(medicine_id)',
    'CREATE INDEX idx_times_schedule ON schedule_times(schedule_id)',
    'CREATE INDEX idx_logs_scheduled ON medicine_logs(scheduled_at)',
    'CREATE INDEX idx_logs_medicine ON medicine_logs(medicine_id, status)',
    'CREATE INDEX idx_health_user_type ON health_records(user_id, type, recorded_at)',
    'CREATE INDEX idx_appt_date ON appointments(appointment_at)',
    'CREATE INDEX idx_queue_created ON sync_queue(created_at)',
  ];
}
